/// Weekly scam-pattern stories (roadmap Phase 2: "Scam alert module").
///
/// Framed as keeping him sharp, not warning him: each one is a short story
/// about a real pattern, the giveaway sign, and what a sensible person does.
/// He can forward each one to friends, which makes him the one who protects
/// others. The team should refresh this list with whatever is circulating in
/// Tamil Nadu that month.
class ScamStory {
  const ScamStory({
    required this.id,
    required this.title,
    required this.story,
    required this.sign,
    required this.action,
  });

  final String id;
  final String title;

  /// Two to four short sentences, told as something that happened.
  final String story;

  /// The giveaway.
  final String sign;

  /// What to do instead.
  final String action;

  String get spoken =>
      '$title. $story அடையாளம்: $sign செய்ய வேண்டியது: $action';

  /// Text forwarded to friends, signed by him.
  String shareText(String from) =>
      '⚠️ $title\n\n$story\n\nஅடையாளம்: $sign\nசெய்ய வேண்டியது: $action\n\n— $from அனுப்பியது';
}

